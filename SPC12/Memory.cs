        public Memory(uint sizeInModes) 
        {
            _mem = new byte[sizeInModes * 4096];

            LoadProgram(_sharedBytes, 0x10);

            // Diagnostics:
            //LoadProgram(_cpuTestProg, 0xa00);
            //LoadProgram(_memTestProg, 0);

            // BOS II monitor & dependencies
            LoadProgram2(_ttyIO, Helpers.GetUshortForOctalString("120"));
            LoadProgram2(_pgsPaperTapeLoaderPunch, Helpers.GetUshortForOctalString("264"));
            LoadProgram2(_pgsBusII, Helpers.GetUshortForOctalString("16500"));
            LoadProgram2(_pgsBusIIModeControl, Helpers.GetUshortForOctalString("704"));
            LoadProgram2(_pgsCasIISourceTapePrep, Helpers.GetUshortForOctalString("16200"));

        }

        public byte ReadByte(int address)
        {
            byte val = _mem[address & 0xfff];
            //Console.WriteLine("Read: {0}-{1}", Helpers.ToOctal(address), Helpers.ToOctal(val, 3));
            return val;
        }

        public void WriteByte(int address, byte value)
        {
            //Console.WriteLine("Write: {0}-{1}", Helpers.ToOctal(address), Helpers.ToOctal(value,3));
            _mem[address & 0xfff] = value;
        }

        private void LoadProgram(string[] data, ushort startAddr)
        {

            foreach (string b in data)
            {
                byte val = Convert.ToByte(b, 8);
                _mem[startAddr] = val;
                startAddr++;
            }
        }

        private void LoadProgram2(string[] data, ushort startAddr)
        {

            foreach (string b in data)
            {
                string[] bytes = b.Split(' ');
                LoadProgram(bytes, startAddr);
                startAddr += (ushort)bytes.Count();
            }
        }

