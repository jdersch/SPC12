        public byte ReadByte(int address, int mode)
        {
            address = address & 0xfff;

            if (address < 0x800)
            {
                return _mem[address];
            }
            else
            {
                // map in the proper block
                return _mem[(address - 0x800) + mode * 0x800];
            }
        }

        public void WriteByte(int address, int mode, byte value)
        {
            address = address & 0xfff;

            if (address < 0x800)
            {
                _mem[address] = value;
            }
            else
            {
                // map in the proper block
                _mem[(address - 0x800) + mode * 0x800] = value;
            }
        }

        private HashSet<ushort> _usedAddresses = new HashSet<ushort>();

        private void LoadProgram(string[] data, ushort startAddr)
        {
            int mode = (startAddr & 0x7fff) >> 12;

            foreach (string b in data)
            {
                if (_usedAddresses.Contains(startAddr))
                {
                    throw new InvalidOperationException("Data clash baby");
                }
                else
                {
                    _usedAddresses.Add(startAddr);
                }

                byte val = Convert.ToByte(b, 8);
                WriteByte(startAddr, mode, val);
                startAddr++;
            }
        }

        private void LoadProgram2(string[] data, ushort startAddr)
        {
            foreach (string b in data)
            {
                string[] bytes = b.Split(' ');
                LoadProgram(bytes, startAddr);
                startAddr += (ushort)bytes.Count();
            }
        }

        private void LoadProgram3(string[] data)
        {
            foreach (string line in data)
            {
                string[] bytes = line.Split(' ');

                ushort address = Convert.ToUInt16(bytes[0], 8);

                string[] dataBytes = new string[bytes.Length - 1];
                Array.ConstrainedCopy(bytes, 1, dataBytes, 0, dataBytes.Length);
                LoadProgram(dataBytes, address);
            }
        }

